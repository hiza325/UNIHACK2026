/* Downloads only the Vietnamese/Latin WOFF2 subsets used by the UI. */
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';

const outputDir = new URL('../fonts/', import.meta.url);
const cssOutput = new URL('../fonts.css', import.meta.url);
const googleFontsUrl = 'https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@400;500;600;700&family=DM+Mono&family=Lora:ital,wght@0,400;0,500;1,400&family=Manrope:wght@600;700;800&display=swap';
const cssResponse = await fetch(googleFontsUrl, {
  headers: { 'User-Agent': 'Mozilla/5.0 AppleWebKit/537.36 Chrome/131 Safari/537.36' },
});
if (!cssResponse.ok) throw new Error(`Failed Google Fonts CSS: ${cssResponse.status}`);
const css = await cssResponse.text();
const blocks = [...css.matchAll(/\/\* ([^*]+) \*\/\s*(@font-face\s*\{.*?\})/gs)];

const selected = blocks.filter(([, subset, block]) => {
  return ['latin', 'vietnamese'].includes(subset);
});

await rm(outputDir, { recursive: true, force: true });
await mkdir(outputDir, { recursive: true });
const emitted = [];
const downloaded = new Set();
for (const [, subset, block] of selected) {
  const remote = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
  if (!remote) continue;
  const family = block.match(/font-family: '([^']+)'/)?.[1] || 'font';
  const style = block.match(/font-style: ([^;]+)/)?.[1] || 'normal';
  const weight = block.match(/font-weight: ([^;]+)/)?.[1] || '400';
  const filename = basename(remote);
  if (!downloaded.has(remote)) {
    const response = await fetch(remote);
    if (!response.ok) throw new Error(`Failed ${remote}: ${response.status}`);
    await writeFile(new URL(filename, outputDir), Buffer.from(await response.arrayBuffer()));
    downloaded.add(remote);
  }
  emitted.push(`/* ${family} · ${style} ${weight} · ${subset} */\n${block.replace(remote, `fonts/${filename}`)}`);
}

await writeFile(cssOutput, `/* Self-hosted subsets generated by scripts/vendor-fonts.mjs. */\n${emitted.join('\n\n')}\n`);
console.log(`Wrote ${emitted.length} @font-face rules to ${join('fonts.css')}`);
